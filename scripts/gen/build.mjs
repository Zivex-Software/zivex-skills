// Assembles each skill's self-contained check script from gen/<name>.rules.js + helpers + runner.
// Usage: node scripts/gen/build.mjs   (output is committed; skills must not depend on repo files at install time)
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const here = import.meta.dirname;
const read = (f) => readFileSync(join(here, f), "utf8");
// helpers.txt holds several top-level declarations; keep only those a rule set references (lint: no unused code).
const helperBlocks = (() => {
  const text = read("helpers.txt");
  const parts = text.split(/\n(?=function |const )/);
  return parts.map((src) => ({ name: /^(?:function|const)\s+(\w+)/.exec(src)?.[1], src }));
})();
const helpersFor = (rules) =>
  helperBlocks
    .filter((b) => b.name && new RegExp(`\\b${b.name}\\b`).test(rules))
    .map((b) => b.src)
    .join("\n");

const targets = {
  security: "aspnet-security/scripts/check-security.mjs",
  performance: "aspnet-performance/scripts/check-performance.mjs",
  data: "aspnet-data-efcore/scripts/check-efcore.mjs",
  api: "aspnet-api-design/scripts/check-api.mjs",
  resilience: "aspnet-resilience/scripts/check-resilience.mjs",
  observability: "aspnet-observability/scripts/check-observability.mjs",
  tests: "dotnet-testing/scripts/check-tests.mjs",
};
// modules.txt is a pool of top-level declarations; a tool gets only what it (transitively) uses, plus the node imports they need.
const moduleBlocks = read("modules.txt")
  .split("\n")
  .filter((l) => !l.startsWith("import "))
  .join("\n")
  .split(/\n(?=function\*? |const )/)
  .map((src) => ({ name: /^(?:function\*?|const)\s+(\w+)/.exec(src)?.[1], src }))
  .filter((b) => b.name);
const FS = ["existsSync", "readdirSync", "readFileSync"];
const PATH = ["basename", "dirname", "join", "relative", "resolve"];
function modulesFor(toolSrc) {
  const own = new Set(
    [...toolSrc.matchAll(/^import\s*\{([^}]*)\}/gm)].flatMap((m) =>
      m[1].split(",").map((x) => x.trim()),
    ),
  );
  const used = new Set();
  let text = toolSrc;
  for (let changed = true; changed;) {
    changed = false;
    for (const b of moduleBlocks) {
      if (!used.has(b.name) && new RegExp(`\\b${b.name}\\b`).test(text)) {
        used.add(b.name);
        text += `\n${b.src}`;
        changed = true;
      }
    }
  }
  const body = moduleBlocks
    .filter((b) => used.has(b.name))
    .map((b) => b.src)
    .join("\n");
  const need = (names) =>
    names.filter((n) => !own.has(n) && new RegExp(`\\b${n}\\b`).test(`${toolSrc}\n${body}`));
  const imp = (names, from) =>
    names.length ? `import { ${names.join(", ")} } from "${from}";\n` : "";
  return `${imp(need(FS), "node:fs")}${imp(need(PATH), "node:path")}${body}\n`;
}

// Standalone tools (scripts/gen/tools/<file>) share the project/module detection snippet (modules.txt).
const tools = {
  "dotnet-module-boundary-check": ["check-boundaries.mjs"],
  "dotnet-module-context": ["module-context.mjs"],
  "dotnet-conventions-bootstrap": ["inspect-repo.mjs"],
  "dotnet-module-contract": ["contract-diff.mjs"],
  "dotnet-verify": ["affected.mjs"],
  "dotnet-module": ["new-module.mjs"],
};
for (const [skill, files] of Object.entries(tools)) {
  for (const file of files) {
    const src = read(join("tools", file));
    const path = join(here, "..", "..", "content", "skills", skill, "scripts", file);
    mkdirSync(dirname(path), { recursive: true });
    const body = src.replace("//@@MODULES@@", () => modulesFor(src));
    writeFileSync(
      path,
      `#!/usr/bin/env node\n// GENERATED by scripts/gen/build.mjs from gen/tools/${file} - edit the sources, not this file.\n${body}`,
    );
    console.log(`wrote ${skill}/scripts/${file}`);
  }
}

for (const [name, out] of Object.entries(targets)) {
  const path = join(here, "..", "..", "content", "skills", out);
  mkdirSync(dirname(path), { recursive: true });
  const rules = read(`${name}.rules.js`);
  const scope = /^\/\/ @scope tests/m.test(rules) ? "tests" : "code";
  const runner = read("runner.txt")
    .replace("__SCOPE__", scope)
    .replace(
      "__SCOPE_TEXT__",
      scope === "tests" ? "test projects only" : "production code (test projects are skipped)",
    );
  const body = `#!/usr/bin/env node\n// GENERATED by scripts/gen/build.mjs from gen/${name}.rules.js - edit the sources, not this file.\n${helpersFor(rules)}\n${rules}\n${runner}`;
  writeFileSync(path, body);
  console.log(`wrote ${out}`);
}
