// Assembles each skill's self-contained check script from gen/<name>.rules.js + helpers + runner.
// Usage: node scripts/gen/build.mjs   (output is committed; skills must not depend on repo files at install time)
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const here = import.meta.dirname;
const read = (f) => readFileSync(join(here, f), "utf8");
// helpers.txt holds several top-level declarations; keep only those a rule set references (lint: no unused code).
const helperBlocks = (() => {
  const text = read("helpers.txt");
  const parts = text.split(/\n(?=function |const )/);
  return parts.map((src) => ({ name: /^(?:function|const)\s+(\w+)/.exec(src)?.[1], src }));
})();
const helpersFor = (rules) =>
  helperBlocks
    .filter((b) => b.name && new RegExp(`\\b${b.name}\\b`).test(rules))
    .map((b) => b.src)
    .join("\n");

const targets = {
  security: "aspnet-security/scripts/check-security.mjs",
  performance: "aspnet-performance/scripts/check-performance.mjs",
  data: "aspnet-data-efcore/scripts/check-efcore.mjs",
  api: "aspnet-api-design/scripts/check-api.mjs",
  resilience: "aspnet-resilience/scripts/check-resilience.mjs",
  observability: "aspnet-observability/scripts/check-observability.mjs",
};
for (const [name, out] of Object.entries(targets)) {
  const path = join(here, "..", "..", "content", "skills", out);
  mkdirSync(dirname(path), { recursive: true });
  const rules = read(`${name}.rules.js`);
  const body = `#!/usr/bin/env node\n// GENERATED by scripts/gen/build.mjs from gen/${name}.rules.js - edit the sources, not this file.\n${helpersFor(rules)}\n${rules}\n${read("runner.txt")}`;
  writeFileSync(path, body);
  console.log(`wrote ${out}`);
}
